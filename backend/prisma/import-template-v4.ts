async function main() {
  const existing = await prisma.competencyVersion.findFirst({ where: { name: VERSION_NAME } });
  if (existing) {
    console.log(`Версия «${VERSION_NAME}» уже существует (${existing.id}) — ничего не делаю.`);
    return;
  }
  const version = await prisma.competencyVersion.create({ data: { name: VERSION_NAME, isDefault: false } });
  let compCount = 0, indCount = 0;
  for (let ci = 0; ci < TEMPLATE.length; ci++) {
    const comp = TEMPLATE[ci];
    await prisma.competencyTemplate.create({
      data: {
        versionId: version.id,
        name: comp.name,
        category: comp.category,
        order: ci,
        isActive: true,
        indicators: { create: comp.indicators.map((ind, ii) => ({ text: ind.text, description: ind.description, order: ii })) },
      },
    });
    compCount++; indCount += comp.indicators.length;
  }
  console.log(`Создана «${VERSION_NAME}»: компетенций ${compCount}, индикаторов ${indCount}.`);
  console.log('Версия НЕ назначена по умолчанию — проверьте её во вкладке «Шаблон оценки» и назначьте вручную.');
}

main().catch(e => { console.error(e); process.exit(1); }).finally(() => prisma.$disconnect());